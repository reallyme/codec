import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { create, fromBinary, toBinary } from "@bufbuild/protobuf";
import * as wasm from "../dist/wasm/reallyme_codec_wasm.js";
import { installReallyMeCodecWasmProvider, processOperation } from "../dist/index.js";
import { CodecApiOperationRequestSchema, CodecApiOperationResponseSchema, CodecErrorReason } from "../dist/proto.js";

wasm.initSync({ module: readFileSync(new URL("../dist/wasm/reallyme_codec_wasm_bg.wasm", import.meta.url)) });
installReallyMeCodecWasmProvider(wasm);

const run = (value, inspect) => {
  const request = toBinary(CodecApiOperationRequestSchema, create(CodecApiOperationRequestSchema, {
    operation: { case: "base64DecodeWithLimits", value: {
      value, limits: { encodedInputBytes: 13_981_016n, decodedOutputBytes: 10_485_760n },
    } },
  }));
  let response;
  try {
    response = processOperation(request);
    inspect(fromBinary(CodecApiOperationResponseSchema, response));
  } finally {
    request.fill(0);
    response?.fill(0);
  }
};

test("WASM admits the exact SSI portrait budgets and rejects either budget plus one", () => {
  const payload = Buffer.alloc(10_485_760, 0x5a);
  try {
    const encoded = payload.toString("base64");
    assert.equal(encoded.length, 13_981_016);
    run(encoded, (response) => {
      assert.equal(response.outcome.case, "result");
      assert.equal(response.outcome.value.result.case, "base64DecodeWithLimits");
      const decoded = response.outcome.value.result.value.value;
      // Generated byte fields can borrow the response buffer. Inspect them
      // before wiping that owner, and keep failures independent of payload size.
      assert.equal(decoded.length, payload.length);
      assert.equal(Buffer.compare(decoded, payload), 0);
    });
    run(`${encoded}A`, (response) => {
      assert.equal(response.outcome.case, "error");
      assert.equal(response.outcome.value.error.value.reason, CodecErrorReason.BASE_INPUT_TOO_LARGE);
    });
    // One more decoded octet fits the same encoded length with less padding.
    const tooLarge = Buffer.alloc(10_485_761, 0x5a);
    try {
      run(tooLarge.toString("base64"), (response) => {
        assert.equal(response.outcome.case, "error");
        assert.equal(response.outcome.value.error.value.reason, CodecErrorReason.BASE_OUTPUT_TOO_LARGE);
      });
    } finally {
      tooLarge.fill(0);
    }
  } finally {
    payload.fill(0);
  }
});

test("WASM keeps the existing Base64 scalar transport at 1 MiB", () => {
  for (const length of [1_048_576, 1_048_577, 1_048_580]) {
    const request = toBinary(CodecApiOperationRequestSchema, create(CodecApiOperationRequestSchema, {
      operation: { case: "base64Decode", value: { value: "A".repeat(length) } },
    }));
    let response;
    try {
      response = processOperation(request);
      const parsed = fromBinary(CodecApiOperationResponseSchema, response);
      if (length === 1_048_576) {
        assert.equal(parsed.outcome.case, "result");
        assert.equal(parsed.outcome.value.result.case, "base64Decode");
      } else {
        assert.equal(parsed.outcome.case, "error");
        assert.equal(parsed.outcome.value.error.value.reason, CodecErrorReason.BASE_INPUT_TOO_LARGE);
      }
    } finally {
      request.fill(0);
      response?.fill(0);
    }
  }
});
